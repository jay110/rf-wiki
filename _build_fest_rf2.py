def dump(name, rows):
    lines = []
    for r in rows:
        lines.append('    ' + json.dumps(r, ensure_ascii=False).replace('"', "'"))
    return 'const %s = [\n%s\n];\n' % (name, ',\n'.join(lines))


def fix_names(rows):
    res = []
    for place, who in rows:
        who = re.sub(r'(^|\u3000)([^\u3000（]+)(?=（|$)', lambda m: m.group(1) + FESTPOS_NAME.get(m.group(2), m.group(2)), who)
        res.append([place, who])
    return res


def main():
    out = []
    out.append('/*')
    out.append(' * RF2 节日日程与节日当天 NPC 分布')
    out.append(' * 由 _build_fest_rf2.py 生成，源：《RF2 攻略合辑.txt》（UTF-16）')
    out.append(' * FEST_RF2：[季节, 日, 中文名, 日文原名, 玩法要点]，日为 null 表示原攻略未标注日期')
    out.append(' * RF2_FESTPOS：[地点, 人物]')
    out.append(' */')
    out.append(dump('FEST_RF2', FEST_RF2))
    out.append(dump('RF2_FESTPOS', fix_names(RF2_FESTPOS)))

    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'js', 'rf2cal.js')
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))

    seas = {}
    undated = []
    for r in FEST_RF2:
        seas.setdefault(r[0], []).append(r[1])
        if r[1] is None:
            undated.append(r[2])
    print('RF2: %d 场' % len(FEST_RF2))
    for s in ['春', '夏', '秋', '冬']:
        print('   %s %d 场: %s' % (s, len(seas.get(s, [])), seas.get(s, [])))
    print('   未标注日期: %s' % (undated or '无'))
    print('   节日 NPC 分布地点: %d 处' % len(RF2_FESTPOS))
    print('已生成 %s' % dst)


if __name__ == '__main__':
    main()
