def to_js_val(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    s = str(v)
    s = s.replace('\\', '\\\\').replace("'", "\\'")
    return "'" + s + "'"


COLS_JS = "[" + ", ".join(to_js_val(c) for c in COLS) + "]"


def build():
    total = 0
    fams = []
    for name, rows in FAMILIES:
        total += len(rows)
        lines = []
        for r in rows:
            line = '[' + ', '.join(to_js_val(c) for c in r) + ']'
            lines.append('            ' + line)
        fams.append(
            "        { name: '%s', cols: COLS, rows: [\n%s\n        ] }" % (name, ',\n'.join(lines))
        )
    body = (
        "// 符文工房 龙之天地（azuma）武器锻造配方。由 _build_azuma_forge.py 生成，勿手改。\n"
        "const COLS = %s;\n"
        "const AZUMA_FORGE = {\n"
        "    src: '%s',\n"
        "    note: '%s',\n"
        "    families: [\n%s\n    ]\n"
        "};\n"
    ) % (COLS_JS, SRC, NOTE, ',\n'.join(fams))

    with open('js/azuma_forge.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)

    print('AZUMA_FORGE 生成完成：%d 类，%d 条武器' % (len(FAMILIES), total))


if __name__ == '__main__':
    build()
