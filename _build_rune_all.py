LINK = re.compile(r'\[\[([^\]|]+)(?:\|([^\]]+))?\]\]')


def plain(s, sep='、'):
    s = LINK.sub(lambda m: (m.group(2) or m.group(1)).strip(), s)
    # <br> 前若已是标点，先吃掉那个标点，避免出现「，；」这种叠标点
    s = re.sub(r'[，、；：]\s*<br\s*/?>', sep.join(['', ''])[0] + '<br>', s)
    s = re.sub(r'<br\s*/?>', sep, s)
    s = re.sub(r'<[^>]+>', '', s)
    s = s.replace('&nbsp;', ' ')
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'[、；]{2,}', lambda m: m.group(0)[0], s)
    return s.strip('、；')


def tables(text, sep='、'):
    out = []
    for block in re.findall(r'\{\|.*?\n\|\}', text, re.S):
        cap = ''
        m = re.search(r'^\|\+\s*(.+)$', block, re.M)
        if m:
            cap = plain(m.group(1))
        head, rows = [], []
        for line in block.split('\n'):
            if line.startswith('!') and not head:
                head = [plain(x, sep) for x in re.split(r'!!', line.lstrip('!'))]
            elif line.startswith('|') and not re.match(r'^\|[-}+]', line):
                cells = [plain(x, sep) for x in re.split(r'\|\|', line.lstrip('|'))]
                if cells and cells != ['']:
                    rows.append(cells)
        out.append((cap, head, rows))
    return out


def read(name):
    with io.open(os.path.join(SNAP, name + '.txt'), encoding='utf-8') as f:
        return f.read()


def norm(v):
    """破折号统一：源表的 - / － / 空串都显示成「—」，其余原样。"""
    v = (v or '').strip()
    return '—' if v in ('', '-', '－', '—', '--') else v


def table_of(name, sep='、'):
    cap, head, rows = tables(read(name), sep)[0]
    fixed = []
    for r in rows:
        assert len(r) == len(head), (name, len(head), len(r), r)
        fixed.append([norm(x) for x in r])
    return cap, head, fixed


